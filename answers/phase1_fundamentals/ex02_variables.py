"""
Exercise 02 — Variables & Types

Task:
    Create variables of type int, float, str, and bool.
    Print each variable and its type.
"""

def main():
    age = 42
    pi = 3.14
    greeting = "Hello"
    is_active = True

    print(age, type(age))
    print(pi, type(pi))
    print(greeting, type(greeting))
    print(is_active, type(is_active))

if __name__ == "__main__":
    main()
